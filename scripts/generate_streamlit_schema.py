"""Compile the native PostgreSQL bootstrap without a connection or credentials.

Run from the repository root with the pinned Python dependencies installed:
    python scripts/generate_streamlit_schema.py
    python scripts/generate_streamlit_schema.py --check
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateIndex, CreateTable

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

TARGET = ROOT / "deploy" / "streamlit" / "schema.sql"


def render_schema() -> str:
    """Use the same table metadata as the runtime's explicit init command."""
    from evidence_streamlit.storage import _sql_schema

    _, metadata, *_ = _sql_schema()
    dialect = postgresql.dialect()
    statements = [
        "-- Generated by scripts/generate_streamlit_schema.py; do not edit manually.",
        "-- Native Streamlit PostgreSQL bootstrap, revision 1. Contains no credentials.",
        "-- Select the intended database/schema before running. This is not a migration.",
        "-- Tables are unqualified, matching the application's configured search_path.",
        "BEGIN;",
    ]
    for table in metadata.sorted_tables:
        statements.append(
            str(CreateTable(table, if_not_exists=True).compile(dialect=dialect)).strip() + ";"
        )
    for index in sorted(
        (index for table in metadata.sorted_tables for index in table.indexes),
        key=lambda item: item.name,
    ):
        statements.append(
            str(CreateIndex(index, if_not_exists=True).compile(dialect=dialect)).strip() + ";"
        )
    statements.extend(
        [
            "CREATE INDEX IF NOT EXISTS ccs_corpus_fts ON ccs_corpus USING GIN (to_tsvector('simple', search_text));",
            """DO $ccs_bootstrap$
BEGIN
    IF EXISTS (SELECT 1 FROM ccs_schema_revision WHERE version <> 1) THEN
        RAISE EXCEPTION 'Evidence AI schema revision is incompatible; use a reviewed migration instead.';
    END IF;
    INSERT INTO ccs_schema_revision (version) VALUES (1)
        ON CONFLICT (version) DO NOTHING;
END;
$ccs_bootstrap$;""",
            "COMMIT;",
        ]
    )
    return "\n".join(line.rstrip() for line in "\n\n".join(statements).splitlines()) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Generate the credential-free PostgreSQL bootstrap."
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Fail if the checked-in SQL differs from current metadata.",
    )
    args = parser.parse_args()
    sql = render_schema()
    if args.check:
        if not TARGET.is_file() or TARGET.read_text(encoding="utf-8") != sql:
            raise SystemExit(
                "Streamlit schema.sql is stale. Run python scripts/generate_streamlit_schema.py."
            )
        print("Streamlit PostgreSQL bootstrap matches current metadata.")
        return
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(sql, encoding="utf-8")
    print("Generated deploy/streamlit/schema.sql (revision 1). No database was accessed.")


if __name__ == "__main__":
    main()
