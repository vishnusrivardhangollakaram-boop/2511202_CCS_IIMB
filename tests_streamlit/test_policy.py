"""Native policy regressions and exact TypeScript-to-Python parity vectors.

Expected vector outputs were generated by the original TypeScript implementation
and checked into policy_vectors.json. Running this suite requires no Node runtime,
model credentials, web requests, or third-party Python testing dependency.
"""

import json
import math
import unittest
from copy import deepcopy
from datetime import datetime, timezone
from pathlib import Path

from evidence_streamlit.policy import (
    POLICY_VERSION,
    claim_parts,
    derive_verdict,
    evaluate_sufficiency,
    get_scenario,
    independent_source_count,
    list_scenarios,
)

VECTOR_FILE = Path(__file__).with_name("policy_vectors.json")
with VECTOR_FILE.open(encoding="utf-8") as source:
    VECTORS = json.load(source)


class PolicyParityTests(unittest.TestCase):
    """Every complete gate and assessment must equal its TypeScript reference."""

    def test_reference_policy_version_matches(self):
        self.assertEqual(VECTORS["policyVersion"], POLICY_VERSION)
        self.assertEqual(VECTORS["schemaVersion"], 1)
        self.assertGreaterEqual(len(VECTORS["cases"]), 40)


def _parity_test(vector):
    def compare(self):
        claim = deepcopy(vector["claim"])
        evidence = deepcopy(vector["evidence"])
        options = deepcopy(vector["options"])
        actual = evaluate_sufficiency(claim, evidence, options)
        self.assertEqual(actual, vector["expectedGate"])
        self.assertEqual(derive_verdict(claim, evidence, actual), vector["expectedAssessment"])
        self.assertEqual(claim, vector["claim"], "Policy mutated its input claim")
        self.assertEqual(evidence, vector["evidence"], "Policy mutated input evidence")
        self.assertEqual(options, vector["options"], "Policy mutated caller options")

    compare.__doc__ = f"TypeScript parity: {vector['id']}"
    return compare


for _index, _vector in enumerate(VECTORS["cases"]):
    setattr(
        PolicyParityTests,
        f"test_vector_{_index:02d}_{_vector['id'].replace(':', '_').replace('-', '_')}",
        _parity_test(_vector),
    )


class NativePolicyTests(unittest.TestCase):
    def setUp(self):
        vector = next(item for item in VECTORS["cases"] if item["id"] == "strong-primary-support")
        self.claim = deepcopy(vector["claim"])
        self.evidence = deepcopy(vector["evidence"])
        self.options = deepcopy(vector["options"])

    def test_datetime_clock_has_same_result_as_iso_clock(self):
        expected = evaluate_sufficiency(self.claim, self.evidence, self.options)
        actual = evaluate_sufficiency(
            self.claim, self.evidence, {"now": datetime(2026, 11, 9, 12, tzinfo=timezone.utc)}
        )
        self.assertEqual(actual, expected)

    def test_naive_datetime_clock_is_interpreted_as_utc(self):
        expected = evaluate_sufficiency(self.claim, self.evidence, self.options)
        self.assertEqual(
            evaluate_sufficiency(self.claim, self.evidence, {"now": datetime(2026, 11, 9, 12)}),
            expected,
        )

    def test_invalid_clock_is_rejected(self):
        with self.assertRaisesRegex(ValueError, "valid evaluation timestamp"):
            evaluate_sufficiency(self.claim, self.evidence, {"now": "not-a-date"})

    def test_default_options_do_not_require_a_clock(self):
        gate = evaluate_sufficiency(self.claim, [])
        self.assertEqual(gate["score"], 0)
        self.assertEqual(gate["decision"], "retrieve_more")

    def test_nonfinite_estimates_never_qualify(self):
        for field in ("quality", "relevance"):
            for value in (math.nan, math.inf, -math.inf):
                with self.subTest(field=field, value=value):
                    evidence = deepcopy(self.evidence)
                    evidence[0][field] = value
                    gate = evaluate_sufficiency(self.claim, evidence, self.options)
                    self.assertEqual(gate["eligibleEvidenceIds"], [])
                    self.assertEqual(gate["score"], 0)

    def test_oversized_python_integer_estimate_fails_closed(self):
        self.evidence[0]["quality"] = 10**1000
        gate = evaluate_sufficiency(self.claim, self.evidence, self.options)
        self.assertEqual(gate["score"], 0)
        self.assertEqual(gate["eligibleEvidenceIds"], [])

    def test_unknown_fixture_has_no_keyword_fallback(self):
        self.assertIsNone(get_scenario("free bus Sunday"))

    def test_fixture_copies_are_isolated(self):
        first = get_scenario("verified-transit")
        first["evidence"][0]["verified"] = False
        self.assertTrue(get_scenario("verified-transit")["evidence"][0]["verified"])

    def test_fixture_data_is_explicitly_synthetic(self):
        scenarios = list_scenarios()
        self.assertEqual(len(scenarios), 5)
        self.assertTrue(all(item["label"] == "Synthetic example" for item in scenarios))
        self.assertTrue(
            all(evidence["origin"] == "demo" for item in scenarios for evidence in item["evidence"])
        )

    def test_independence_function_counts_unknown_origin_as_zero(self):
        self.evidence[0]["independenceKey"] = ""
        self.assertEqual(independent_source_count(self.evidence), 0)

    def test_normalization_preserves_first_nonempty_atomic_wording(self):
        self.assertEqual(
            claim_parts(
                {"text": "fallback", "parts": ["First claim", " FIRST  CLAIM ", "", "Second claim"]}
            ),
            ["First claim", "Second claim"],
        )

    def test_all_automatic_labels_remain_preliminary(self):
        for scenario in list_scenarios():
            gate = evaluate_sufficiency(
                scenario["claim"], scenario["evidence"], {"now": scenario["evaluationDate"]}
            )
            assessment = derive_verdict(scenario["claim"], scenario["evidence"], gate)
            self.assertIs(assessment["preliminary"], True)


if __name__ == "__main__":
    unittest.main()
